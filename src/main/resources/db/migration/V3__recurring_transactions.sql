-- F9: recurring incomes/expenses. Each rule creates a normal income/expense on every due date.
create table if not exists tbl_recurring (
    id bigint generated by default as identity primary key,
    profile_id bigint not null references tbl_profiles (id),
    category_id bigint not null references tbl_categories (id),
    type varchar(10) not null,
    name varchar(255) not null,
    icon varchar(255),
    amount numeric(38, 2) not null,
    frequency varchar(10) not null,
    start_date date not null,
    end_date date,
    next_date date,
    active boolean not null default true,
    version bigint not null default 0,
    created_at timestamp(6),
    updated_at timestamp(6)
);
create index if not exists idx_recurring_profile on tbl_recurring (profile_id);
create index if not exists idx_recurring_due on tbl_recurring (active, next_date);

-- Movements created by a rule remember it (deleting the rule keeps them)
alter table tbl_incomes add column if not exists recurring_id bigint references tbl_recurring (id) on delete set null;
alter table tbl_expenses add column if not exists recurring_id bigint references tbl_recurring (id) on delete set null;
