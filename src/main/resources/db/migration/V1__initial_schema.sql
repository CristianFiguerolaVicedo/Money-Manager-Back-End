-- Initial schema (PostgreSQL), equal to what Hibernate generated with ddl-auto=update.
-- On databases that already had these tables Flyway skips this script (baseline = 1).

create table if not exists tbl_profiles (
    id bigint generated by default as identity primary key,
    full_name varchar(255),
    email varchar(255) unique,
    password varchar(255),
    profile_image_url varchar(255),
    created_at timestamp(6),
    updated_at timestamp(6),
    is_active boolean,
    activation_token varchar(255),
    activation_token_expires_at timestamp(6),
    password_reset_token_hash varchar(255),
    password_reset_expires_at timestamp(6)
);

create table if not exists tbl_categories (
    id bigint generated by default as identity primary key,
    name varchar(255),
    created_at timestamp(6),
    updated_at timestamp(6),
    type varchar(255),
    icon varchar(255),
    profile_id bigint not null references tbl_profiles (id)
);

create table if not exists tbl_incomes (
    id bigint generated by default as identity primary key,
    name varchar(255),
    icon varchar(255),
    date date,
    amount numeric(38, 2),
    created_at timestamp(6),
    updated_at timestamp(6),
    category_id bigint not null references tbl_categories (id),
    profile_id bigint not null references tbl_profiles (id)
);

create table if not exists tbl_expenses (
    id bigint generated by default as identity primary key,
    name varchar(255),
    icon varchar(255),
    date date,
    amount numeric(38, 2),
    created_at timestamp(6),
    updated_at timestamp(6),
    category_id bigint not null references tbl_categories (id),
    profile_id bigint not null references tbl_profiles (id)
);
