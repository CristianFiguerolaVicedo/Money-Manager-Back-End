-- Audit: sessions renewed with a refresh token kept in an HttpOnly cookie.
-- Only a SHA-256 hash of each token is stored; tokens of one login share a family_id so that
-- reusing an already-rotated token revokes the whole family (stolen-token detection).
create table if not exists tbl_refresh_tokens (
    id bigint generated by default as identity primary key,
    profile_id bigint not null references tbl_profiles (id) on delete cascade,
    token_hash varchar(64) not null unique,
    family_id varchar(36) not null,
    expires_at timestamp(6) not null,
    created_at timestamp(6),
    revoked_at timestamp(6)
);
create index if not exists idx_refresh_tokens_profile on tbl_refresh_tokens (profile_id);
create index if not exists idx_refresh_tokens_family on tbl_refresh_tokens (family_id);

-- Access tokens issued before this moment are rejected (password change, password reset, "log out everywhere")
alter table tbl_profiles add column if not exists tokens_valid_after timestamp(6);
