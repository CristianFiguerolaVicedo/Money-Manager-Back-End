alter table tbl_profiles add column if not exists email_daily_reminder boolean not null default false;
alter table tbl_profiles add column if not exists email_daily_summary boolean not null default false;
alter table tbl_profiles add column if not exists email_monthly_report boolean not null default false;
alter table tbl_profiles add column if not exists email_unsubscribe_token varchar(64);

-- F8: monthly budget per expense category
create table if not exists tbl_budgets (
    id bigint generated by default as identity primary key,
    profile_id bigint not null references tbl_profiles (id),
    category_id bigint not null references tbl_categories (id),
    amount numeric(38, 2) not null,
    created_at timestamp(6),
    updated_at timestamp(6),
    constraint uk_budget_category unique (category_id)
);
create index if not exists idx_budgets_profile on tbl_budgets (profile_id);

-- Scheduled email jobs: one row per job and day, so a retried trigger never sends twice
create table if not exists tbl_job_runs (
    id bigint generated by default as identity primary key,
    job_name varchar(50) not null,
    run_date date not null,
    started_at timestamp(6),
    emails_sent integer,
    constraint uk_job_run unique (job_name, run_date)
);
