-- F15: free-text note on incomes/expenses
alter table tbl_incomes add column if not exists note varchar(500);
alter table tbl_expenses add column if not exists note varchar(500);

-- F15: private attachments (receipts, invoices) stored in the database, only served to their owner
create table if not exists tbl_attachments (
    id bigint generated by default as identity primary key,
    profile_id bigint not null references tbl_profiles (id),
    income_id bigint references tbl_incomes (id) on delete cascade,
    expense_id bigint references tbl_expenses (id) on delete cascade,
    filename varchar(255) not null,
    content_type varchar(100) not null,
    size_bytes integer not null,
    data bytea not null,
    created_at timestamp(6),
    constraint ck_attachment_owner check ((income_id is null) <> (expense_id is null))
);
create index if not exists idx_attachments_income on tbl_attachments (income_id);
create index if not exists idx_attachments_expense on tbl_attachments (expense_id);
create index if not exists idx_attachments_profile on tbl_attachments (profile_id);
