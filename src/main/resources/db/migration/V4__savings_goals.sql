-- F14: savings goals and the contributions (or withdrawals, negative) made to them
create table if not exists tbl_goals (
    id bigint generated by default as identity primary key,
    profile_id bigint not null references tbl_profiles (id),
    name varchar(100) not null,
    icon varchar(255),
    target_amount numeric(38, 2) not null,
    deadline date,
    created_at timestamp(6),
    updated_at timestamp(6)
);
create index if not exists idx_goals_profile on tbl_goals (profile_id);

create table if not exists tbl_goal_contributions (
    id bigint generated by default as identity primary key,
    goal_id bigint not null references tbl_goals (id) on delete cascade,
    amount numeric(38, 2) not null,
    date date not null,
    note varchar(255),
    created_at timestamp(6)
);
create index if not exists idx_goal_contributions_goal on tbl_goal_contributions (goal_id);
